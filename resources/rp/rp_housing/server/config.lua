-- Жильё (шаг 11, решения владельца 2026-11-06). Цены и сроки — черновые, баланс — шаг 13.
-- Места — только уникальные в общем мире, на настоящих дверях игры (open77_doors). Ставит
-- администрация в F3 → «Жильё» (право rp.housing); аренда и покупка — сайт realty.nc в NetOS.
-- Ключ — щепка в нейропорте (rp_identity, предъявляемая): жильё оформляется на её SIN, двери
-- отпирает щепка владельца или SIN из списка доступа; аннулированная щепка не открывает.
-- Счёт дома — у любого жилья: с него раз в неделю аренда (арендованное) или коммунальные (купленное).

HousingConfig = {
    permission = "rp.housing",
    moneySink = "sys:rp.money",       -- аренда, коммунальные — городу (деньги сгорают)
    accountPrefix = "soc:rp.house.",  -- счёт дома: soc:rp.house.<id>; с него — аренда или коммунальные

    weekSeconds = 7 * 24 * 3600,      -- период аренды и коммунальных
    graceDays = 3,                    -- долг: столько дней жильё заперто (и для владельца), потом выселение
    checkSeconds = 300,               -- как часто проверяется списание со счёта дома
    depositMax = 10000000,            -- взнос на счёт дома за раз — не больше

    accessRadius = 2.5,               -- щепка с доступом рядом с дверью — она отпирается сама
    holdSeconds = 4,                  -- после ухода последнего с доступом — снова заперта
    accessMax = 10,                   -- SIN в списке доступа (кроме владельца) — не больше

    -- Продажа с рук (только купленное): покупатель — рядом со щепкой указанного SIN в нейропорте
    -- и подтверждает /house accept. Арендованное не передаётся.
    offerRadius = 4,
    offerSeconds = 90,

    -- Взлом (решение владельца: всегда, и при владельце вне игры): отмычка, долго и шумно.
    lockpickItem = "lockpick",
    lockpickRadius = 2.5,
    lockpickSeconds = 45,
    breakOpenSeconds = 20,            -- взломанная дверь открыта столько, потом снова заперта
    noiseRadius = 30,                 -- кто ближе — слышит взлом

    doorSearchRadius = 6,             -- F3: «ближайшая дверь» — не дальше
    kinds = { apartment = "Квартира", house = "Дом" },
    utcOffsetHours = 3,               -- даты в текстах (оплачено до …) — по Москве
}
