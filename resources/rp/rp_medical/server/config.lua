-- Ранение, медики, больницы. Больницы — точки администрации (rp.hospital add).
--
-- Когда здоровье падает до нуля, персонаж «ранен»: сидит в позе downedAnimation под
-- неуязвимостью и ждёт.
-- G — вызвать медиков: им приходит вызов с меткой. Если медиков на смене нет, едет
-- NPC-бригада и поднимает на месте за плату. Через giveUpSeconds можно нажать H —
-- очнуться в ближайшей больнице за плату. Медик на смене поднимает командой /revive.

MedicalConfig = {
    -- Поза раненого — профиль open77_animations: "wounded" (сидит на земле, держится за живот),
    -- "arrested" (лежит лицом вниз), "cower" и др. "lie" (на спине) рассчитана на высоту
    -- кровати: на ровной земле персонаж висит в воздухе.
    downedAnimation = "wounded",
    downedHealth = 0.05,     -- здоровье (доля) раненого; урон по нему не проходит (неуязвимость)

    giveUpSeconds = 300,     -- через сколько раненый может уйти в больницу (H)
    hospitalPrice = 500,     -- €$ за лечение в больнице (со счёта; не хватает — сколько есть)
    hospitalHealth = 0.6,    -- с каким здоровьем (доля) выходит из больницы

    callCooldownSeconds = 60, -- повторный вызов медиков не чаще
    npcArriveSeconds = 90,   -- через сколько приезжает NPC-бригада, если медиков на смене нет
    npcPrice = 1000,         -- €$ за NPC-бригаду
    npcHealth = 0.4,         -- с каким здоровьем поднимает NPC-бригада

    reviveDistance = 3,      -- /revive: как близко медик должен стоять к раненому
    reviveSeconds = 8,       -- сколько длится реанимация (медик должен оставаться рядом)
    reviveHealth = 0.5,      -- с каким здоровьем поднимает медик

    callPermission = "ems.basic",   -- кому приходят вызовы (право работы, только на смене)
    revivePermission = "ems.revive", -- кто может /revive (право работы, только на смене)
}
