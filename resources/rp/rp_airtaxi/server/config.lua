-- Аэротакси. Два способа: вызвать к себе (/airtaxi, летит к метке на карте, см. call) и
-- рейс с площадки. Площадки ставит администрация в игре (rp.airpad add <название>): там,
-- где стоит администратор, лицом туда, куда пассажир будет смотреть по прилёте. С площадки
-- игрок летит на любую другую. Оплата со счёта, деньги сгорают в sys:rp.money
-- (перевозчик государственный).
--
-- Полёт — АВ-бот (bot): АВ прилетает, пассажир садится, АВ летит к точке и садится; его
-- видят все. Не вышло (АВ не создался, игрок не сел) — запасная сцена: экран темнеет,
-- пассажир переносится к месту прилёта в свой bucket, через время полёта появляется там.

AirTaxiConfig = {
    useDistance = 4,      -- метров до площадки, чтобы улететь (проверяет сервер)
    sessionSeconds = 120, -- сколько окно выбора действует без повторного открытия
    pointHeight = 1.0,    -- подсказка — на столько метров выше ног администратора

    -- Цена: base + perKm за километр по прямой, округление до 10 €$.
    price = { base = 150, perKm = 120 },
    -- Время полёта: seconds + perKmSeconds за километр, не больше maxSeconds.
    flight = { seconds = 8, perKmSeconds = 4, maxSeconds = 25 },
    -- Вызов к себе (/airtaxi): летит к метке на карте. Цена — как у рейса по расстоянию плюс fee.
    -- Пока АВ летит (waitSeconds), игрок ждёт на месте: отойти дальше stayRadius, ранение,
    -- наручники — вызов отменяется. Так от полиции на такси не уйти.
    call = { fee = 300, waitSeconds = 45, stayRadius = 30, minMeters = 200, cooldownSeconds = 60 },
    -- АВ-бот. model — запись машины-АВ; altitude — высота полёта над точками, м; speed — м/с
    -- (быстрее, если иначе крейсерский участок дольше maxCruiseSeconds); arriveSeconds —
    -- снижение, takeoffSeconds — набор высоты; sideOffset — АВ садится на столько метров
    -- правее игрока; seat — место пассажира; tickMs — как часто сервер двигает АВ.
    bot = { enabled = true, model = "Vehicle.av_zetatech_valgus", altitude = 80, speed = 70, maxCruiseSeconds = 60,
            arriveSeconds = 8, takeoffSeconds = 6, sideOffset = 8, seat = "rearLeft", tickMs = 50,
            boardTimeoutMs = 8000, departDelayMs = 3000 },
    flightBucketBase = 62000, -- + playerId: bucket на время полёта

    -- Звук взлёта у площадки (слышат все рядом). Звук из каталога игры, в игре не проверен;
    -- nil — без звука.
    departSound = "amb_g_city_el_vehicles_av_mix_rnd_04_elegant",
}
